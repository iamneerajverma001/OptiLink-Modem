/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{
  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* Configure the system clock */
  SystemClock_Config();

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_DMA_Init();
  MX_ADC1_Init();
  MX_TIM3_Init();
  MX_USART3_UART_Init();
  MX_USB_OTG_FS_PCD_Init();
  
  /* USER CODE BEGIN 2 */
  extern UART_HandleTypeDef huart3;
  
  // 1. INITIALIZE ALL LIFI LAYERS (THIS WAS MISSING!)
  LiFi_DSP_Init();
  LiFi_DPLL_Init();
  LiFi_MAC_Init();
  LiFi_HW_Init(); // This turns on the ADC and Timer!
  
  HAL_UART_Transmit(&huart3, (uint8_t*)"\r\n[RX BOOT] LiFi modem online. Listening for framed packets...\r\n", 67, 100);
  /* USER CODE END 2 */

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  
  uint32_t lastRxTick = 0;
  uint32_t burstBytes = 0;
  float sumAmp = 0.0f;
  float sumPhase = 0.0f;
  uint32_t packetCount = 0;
  uint8_t receivingMessage = 0; // Tracks if a sentence is currently in progress

  const LIFI_DIAG* diag = LiFi_Diag_Get();

  while (1)
  {
      // 1. IF A CHUNK ARRIVES: Print it on the SAME line and record the physics
      if (macPayloadReady == 1) {
          char statusLine[128];
          snprintf(statusLine, sizeof(statusLine), "\r\n[RX STAT] lock=%u sync=%u seq=%u ok=%lu fail=%lu dup=%lu ooo=%lu amp=%d noise=%d phase=%.1f crc=%lu inv=%lu len=%lu\r\n",
                   diag->lastLockState,
                   macSyncFound,
                   macPacketSequence,
                   (unsigned long)diag->packetsGood,
                   (unsigned long)diag->packetsBad,
                   (unsigned long)diag->duplicatePackets,
                   (unsigned long)diag->outOfOrderPackets,
                   (int)diag->lastAmplitude,
                   (int)diag->lastNoise,
                   diag->lastPhaseError,
                   (unsigned long)diag->crcErrors,
                   (unsigned long)diag->invalidTransitionCount,
                   (unsigned long)diag->lastPacketLength);
          HAL_UART_Transmit(&huart3, (uint8_t*)statusLine, strlen(statusLine), 100);
          HAL_UART_Transmit(&huart3, (uint8_t*)macPayloadBuffer, macExpectedLength, 100);
          
          burstBytes += macExpectedLength;
          sumAmp += signalAmplitude;
          
          // Use absolute value for phase drift so negative drift doesn't cancel positive drift
          if (pllPhaseError < 0) sumPhase -= pllPhaseError; 
          else sumPhase += pllPhaseError;
          
          packetCount++;
          
          lastRxTick = HAL_GetTick(); // Reset the silence timer
          receivingMessage = 1;       // Flag that we are in the middle of a sentence
          macPayloadReady = 0; 
      }
      
      // 2. IF 2.5 SECONDS PASS WITH NO NEW DATA: Print the Telemetry Summary
      if (receivingMessage == 1 && (HAL_GetTick() - lastRxTick > 2500)) {
          
          char rxDash[256];
          
          // Notice we use %d (Integer) and cast the floats (int) to bypass the STM32 Bug!
          sprintf(rxDash, 
              "\r\n-------------------------------------------------\r\n"
              "[LINK METRICS] Payload: %lu Bytes | Avg Amp: %d | Avg Phase Drift: %d | Ok: %lu | Fail: %lu | Lock Events: %lu\r\n"
              "-------------------------------------------------\r\n> ", 
              burstBytes, 
              (int)(sumAmp / packetCount), 
              (int)(sumPhase / packetCount),
              (unsigned long)diag->packetsGood,
              (unsigned long)diag->packetsBad,
              (unsigned long)diag->pllLockEvents
          );
          
          HAL_UART_Transmit(&huart3, (uint8_t*)rxDash, strlen(rxDash), 100);
          
          // Reset the trackers for the next sentence
          burstBytes = 0;
          sumAmp = 0.0f;
          sumPhase = 0.0f;
          packetCount = 0;
          receivingMessage = 0; 
      }
      
      HAL_Delay(2);
    /* USER CODE END WHILE */
  }
  
    /* USER CODE BEGIN 3 */
  
  /* USER CODE END 3 */
}

